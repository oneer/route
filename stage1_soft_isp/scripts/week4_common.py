# 中文注释：从输入路径提取稳定样本名，用作图像、JSON 和报告文件的前缀。
# ????? sample_id ???????? ISP ????????????
def sample_id(raw_path: Path) -> str:
    # ??????????????????????
    return raw_path.name.split("_", 1)[0]


# 中文注释：统计 RGB 图像的形状、范围和通道均值，帮助诊断色彩偏移。
# ????? describe_rgb ???????? ISP ????????????
