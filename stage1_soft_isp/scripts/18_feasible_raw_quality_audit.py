# 中文注释：_inject_defects 在 Bayer 同色位置注入高/低坏点，构造可重复的 DPC 检测真值。
# ????? _inject_defects ???????? ISP ????????????
def _inject_defects(
    # ????? NumPy ????????????????????
    raw_blc: np.ndarray,
    # ??????????????????????????????
    white_level: int,
    # ??????????????????????????????
    count: int,
    # ???????? margin: int?????????????
    margin: int = 16,
# ????? NumPy ????????????????????
) -> tuple[np.ndarray, np.ndarray]:
    # ?????????????????????????????
    injected = raw_blc.copy()
    # ????? NumPy ????????????????????
    mask = np.zeros(raw_blc.shape, dtype=bool)
    # ?????????????????????????????
    height, width = raw_blc.shape
    # ???????? usable_h?????????????
    usable_h = max(height - 2 * margin, 1)
    # ???????? usable_w?????????????
    usable_w = max(width - 2 * margin, 1)
    # ????? NumPy ????????????????????
    grid = int(np.ceil(np.sqrt(count)))
    # ????? NumPy ????????????????????
    ys = np.linspace(margin, margin + usable_h - 3, grid, dtype=int)
    # ????? NumPy ????????????????????
    xs = np.linspace(margin, margin + usable_w - 3, grid, dtype=int)
    # ???????? phases?????????????
    phases = [(0, 0), (0, 1), (1, 0), (1, 1)]

    # ???????? placed?????????????
    placed = 0
    # ??????????????????????????????
    for y in ys:
        # ??????????????????????????????
        for x in xs:
            # ???????????????????????????
            if placed >= count:
                # ???????????????????
                break
            # ???????? phase_y, phase_x?????????????
            phase_y, phase_x = phases[placed % len(phases)]
            # ???????? y_base?????????????
            y_base = int(y - (y % 2) + phase_y)
            # ???????? x_base?????????????
            x_base = int(x - (x % 2) + phase_x)
            # ?????????????????????????????
            local = raw_blc[max(0, y_base - 2) : y_base + 3, max(0, x_base - 2) : x_base + 3]
            # ????? NumPy ????????????????????
            local_median = float(np.median(local))
            # ??????????????????????????
            value = 0 if local_median > white_level * 0.5 else int(white_level)
            # ????? NumPy ????????????????????
            injected[y_base, x_base] = np.asarray(value, dtype=raw_blc.dtype)
            # ???????? mask[y_base, x_base]?????????????
            mask[y_base, x_base] = True
            # ???????? placed +?????????????
            placed += 1
        # ???????????????????????????
        if placed >= count:
            # ???????????????????
            break
    # ??????????????????????
    return injected, mask


# 中文注释：_run_dpc_injection 在合成坏点样本上跑 DPC，输出 precision/recall 评价检测能力。
# ????? _run_dpc_injection ???????? ISP ????????????
def _run_dpc_injection(
    # ????? NumPy ????????????????????
    raw_blc: np.ndarray,
    # ????? Bayer/CFA ??????????????? RGB ???
    bayer_pattern: str,
    # ??????????????????????????????
    white_level: int,
    # ??????????????????????????????
    count: int,
    # ???????? mad_k: float?????????????
    mad_k: float = 12.0,
    # ??????????????????????????????
    min_delta: int = 1024,
# ??????????????????????????????
) -> dict[str, float | int]:
    # ??????????????????????????????
    injected, injected_mask = _inject_defects(raw_blc, white_level, count=count)
    # ??????????????????????????????
    detection = detect_defects(injected, bayer_pattern, min_delta=min_delta, mad_k=mad_k)
    # ?????????????????????????????
    detected_mask = merge_channel_masks(raw_blc.shape, bayer_pattern, detection["masks"])
    # ??????????????????????????????
    repaired = repair_defects(injected, bayer_pattern, detection)
    # ????? NumPy ????????????????????
    residual = np.abs(repaired.astype(np.int32) - raw_blc.astype(np.int32))

    # ????? NumPy ????????????????????
    injected_total = int(np.count_nonzero(injected_mask))
    # ????? NumPy ????????????????????
    true_positive = int(np.count_nonzero(detected_mask & injected_mask))
    # ????? NumPy ????????????????????
    false_negative = int(np.count_nonzero(injected_mask & ~detected_mask))
    # ????? NumPy ????????????????????
    extra_detection = int(np.count_nonzero(detected_mask & ~injected_mask))
    # ??????????????????????
    return {
        # ??????????????????????????????
        "injected_total": injected_total,
        # ??????????????????????????????
        "min_delta": int(min_delta),
        # ??????????????????????????????
        "mad_k": float(mad_k),
        # ????? NumPy ????????????????????
        "detected_total": int(np.count_nonzero(detected_mask)),
        # ??????????????????????????????
        "true_positive": true_positive,
        # ??????????????????????????????
        "false_negative": false_negative,
        # ??????????????????????????????
        "extra_detection": extra_detection,
        # ??????????????????????????????
        "injected_recall": float(true_positive / max(injected_total, 1)),
        # ??????????????????????????????
        "extra_detection_fraction": float(extra_detection / max(detected_mask.size, 1)),
        # ????? NumPy ????????????????????
        "mean_residual_after_repair_on_injected": float(np.mean(residual[injected_mask])) if injected_total else 0.0,
    # ?????????????????????
    }


# 中文注释：_run_dpc_scan 在真实 RAW 上扫描异常像素数量，作为潜在坏点或热噪声提示。
