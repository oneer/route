# 中文注释：_roi_from_percentile 按亮度分位点选择 ROI，用来稳定抽取暗部/中间调/高光区域。
# ????? _roi_from_percentile ???????? ISP ????????????
def _roi_from_percentile(raw: np.ndarray, percentile: float, roi_size: int, stride: int) -> tuple[int, int, int, int]:
    # ????? NumPy ????????????????????
    target = float(np.percentile(raw, percentile))
    # ???????? height, width?????????????
    height, width = raw.shape
    # ???????? best: tuple[float, int, int] | None?????????????
    best: tuple[float, int, int] | None = None
    # ??????????????????????????????
    for y in range(0, height - roi_size + 1, stride):
        # ??????????????????????????????
        for x in range(0, width - roi_size + 1, stride):
            # ???????? roi?????????????
            roi = raw[y : y + roi_size, x : x + roi_size]
            # ????? NumPy ????????????????????
            score = abs(float(np.mean(roi)) - target)
            # ???????????????????????????
            if best is None or score < best[0]:
                # ????????????????????????
                best = (score, x, y)
    # ???????????????????????????
    if best is None:
        # ????????????????????????????
        raise ValueError(f"ROI size {roi_size} is too large for RAW shape {raw.shape}")
    # ??????????????????????
    return (best[1], best[2], roi_size, roi_size)


# 中文注释：_edge_roi 根据梯度强度寻找边缘区域，为锐度和 MTF50 代理指标提供输入。
# ????? _edge_roi ???????? ISP ????????????
def _edge_roi(raw: np.ndarray, roi_size: int, stride: int) -> tuple[int, int, int, int]:
    # ????? NumPy ????????????????????
    data = raw.astype(np.float32)
    # ????? NumPy ????????????????????
    gx = np.zeros_like(data)
    # ????? NumPy ????????????????????
    gy = np.zeros_like(data)
    # ????? NumPy ????????????????????
    gx[:, 1:] = np.abs(data[:, 1:] - data[:, :-1])
    # ????? NumPy ????????????????????
    gy[1:, :] = np.abs(data[1:, :] - data[:-1, :])
    # ???????? grad?????????????
    grad = gx + gy

    # ???????? height, width?????????????
    height, width = raw.shape
    # ???????? best: tuple[float, int, int] | None?????????????
    best: tuple[float, int, int] | None = None
    # ??????????????????????????????
    for y in range(0, height - roi_size + 1, stride):
        # ??????????????????????????????
        for x in range(0, width - roi_size + 1, stride):
            # ????? NumPy ????????????????????
            score = float(np.mean(grad[y : y + roi_size, x : x + roi_size]))
            # ???????????????????????????
            if best is None or score > best[0]:
                # ????????????????????????
                best = (score, x, y)
    # ???????????????????????????
    if best is None:
        # ????????????????????????????
        raise ValueError(f"ROI size {roi_size} is too large for RAW shape {raw.shape}")
    # ??????????????????????
    return (best[1], best[2], roi_size, roi_size)


# 中文注释：_center_even_crop 从中心裁剪偶数尺寸 RAW，保持 Bayer 2x2 相位不变。
# ????? _center_even_crop ???????? ISP ????????????
def _center_even_crop(raw: np.ndarray, max_side: int = 1024) -> np.ndarray:
    # ???????? height, width?????????????
    height, width = raw.shape
    # ???????? crop_h?????????????
    crop_h = min(height, max_side)
    # ???????? crop_w?????????????
    crop_w = min(width, max_side)
    # ???????? crop_h -?????????????
    crop_h -= crop_h % 2
    # ???????? crop_w -?????????????
    crop_w -= crop_w % 2
    # ???????? y?????????????
    y = ((height - crop_h) // 2) // 2 * 2
    # ???????? x?????????????
    x = ((width - crop_w) // 2) // 2 * 2
    # ??????????????????????
    return raw[y : y + crop_h, x : x + crop_w]


# 中文注释：_raw_preview 用分位点拉伸生成 RAW 灰度预览，让审计报告可以直接观察曝光和结构。
# ????? _raw_preview ???????? ISP ????????????
def _raw_preview(raw: np.ndarray, black_level: float, white_level: float) -> np.ndarray:
    # ????? NumPy ????????????????????
    display_max = min(float(np.percentile(raw, 99.5)), float(white_level))
    # ?????????????????????????????
    display_min = float(black_level)
    # ???????????????????????????
    if display_max <= display_min:
        # ????? NumPy ????????????????????
        display_max = float(np.max(raw))
    # ????? NumPy ????????????????????
    preview = (raw.astype(np.float32) - display_min) / max(display_max - display_min, 1e-6)
    # ??????????????????????
    return np.clip(preview, 0.0, 1.0)


