# 中文注释：根据 rawpy/LibRaw flip 编码对图像做显示方向变换。
# ????? apply_rawpy_orientation ???????? ISP ????????????
def apply_rawpy_orientation(image: np.ndarray, flip: int) -> np.ndarray:
    # ?????????????????????? ISP ???????????
    """Apply LibRaw/rawpy display orientation to an image array."""
    # ???????????????????????????
    if flip == 0:
        # ??????????????????????
        return image
    # ???????????????????????????
    if flip == 1:
        # ??????????????????????
        return np.fliplr(image)
    # ???????????????????????????
    if flip == 2:
        # ??????????????????????
        return np.flipud(image)
    # ???????????????????????????
    if flip == 3:
        # ??????????????????????
        return np.rot90(image, 2)
    # ???????????????????????????
    if flip == 4:
        # ??????????????????????
        return np.transpose(image, (1, 0, 2)) if image.ndim == 3 else np.transpose(image)
    # ???????????????????????????
    if flip == 5:
        # ??????????????????????
        return np.rot90(image, 1)
    # ???????????????????????????
    if flip == 6:
        # ??????????????????????
        return np.rot90(image, -1)
    # ???????????????????????????
    if flip == 7:
        # ????? NumPy ????????????????????
        rotated = np.rot90(image, -1)
        # ??????????????????????
        return np.fliplr(rotated)
    # ??????????????????????
    return image


# 中文注释：把轴对齐 ROI 框转换到显示方向坐标系。
# ????? transform_box_for_orientation ???????? ISP ????????????
def transform_box_for_orientation(
    # ??????????????????????????????
    x: float,
    # ??????????????????????????????
    y: float,
    # ??????????????????????????????
    w: float,
    # ??????????????????????????????
    h: float,
    # ??????????????????????????????
    image_shape: tuple[int, int],
    # ??????????????????????????????
    flip: int,
# ??????????????????????????????
) -> tuple[float, float, float, float]:
    # ?????????????????????? ISP ???????????
    """Transform an axis-aligned box into display-oriented image coordinates."""
    # ???????? height, width?????????????
    height, width = image_shape
    # ????? NumPy ????????????????????
    corners = np.array(
        # ?????????????????????? ISP ???????????
        [
            # ??????????????????????????????
            [x, y],
            # ??????????????????????????????
            [x + w, y],
            # ??????????????????????????????
            [x, y + h],
            # ??????????????????????????????
            [x + w, y + h],
        # ?????????????????????
        ],
        # ????? NumPy ????????????????????
        dtype=np.float32,
    # ?????????????????????
    )

    # ???????? xs?????????????
    xs = corners[:, 0]
    # ???????? ys?????????????
    ys = corners[:, 1]
    # ???????????????????????????
    if flip == 0:
        # ???????? tx, ty?????????????
        tx, ty = xs, ys
    # ????????????????????????
    elif flip == 1:
        # ???????? tx, ty?????????????
        tx, ty = width - xs, ys
    # ????????????????????????
    elif flip == 2:
        # ???????? tx, ty?????????????
        tx, ty = xs, height - ys
    # ????????????????????????
    elif flip == 3:
        # ???????? tx, ty?????????????
        tx, ty = width - xs, height - ys
    # ????????????????????????
    elif flip == 4:
        # ???????? tx, ty?????????????
        tx, ty = ys, xs
    # ????????????????????????
    elif flip == 5:
        # ???????? tx, ty?????????????
        tx, ty = ys, width - xs
    # ????????????????????????
    elif flip == 6:
        # ???????? tx, ty?????????????
        tx, ty = height - ys, xs
    # ????????????????????????
    elif flip == 7:
        # ???????? tx, ty?????????????
        tx, ty = height - ys, width - xs
    # ????????????????????
    else:
        # ???????? tx, ty?????????????
        tx, ty = xs, ys

    # ????? NumPy ????????????????????
    x0 = float(np.min(tx))
    # ????? NumPy ????????????????????
    y0 = float(np.min(ty))
    # ????? NumPy ????????????????????
    x1 = float(np.max(tx))
    # ????? NumPy ????????????????????
    y1 = float(np.max(ty))
    # ??????????????????????
    return x0, y0, x1 - x0, y1 - y0
